def act_user_update(conn, actor, params):
    _require(params, "user_id")
    user_id = int(params["user_id"])
    before_row = db.get_user(conn, user_id)
    if before_row is None:
        raise ApiError("user not found", 404)
    before = dict(before_row)
    new_email = (params.get("email") or before["email"]).strip().lower()
    new_role = params.get("role") or before["role"]
    email_changed = new_email != before["email"]
    role_changed = new_role != before["role"]
    if email_changed:
        existing = db.get_user_by_email(conn, new_email)
        if existing and existing["id"] != user_id:
            raise ApiError(f"a user with email {new_email} already exists.")
    if (
        role_changed
        and before["role"] == "owner"
        and new_role != "owner"
        and db.count_owners_for_account(conn, before["account_id"]) <= 1
    ):
        raise ApiError("cannot demote the last owner of an account.")
    if email_changed:
        db.record_audit(
            conn,
            actor=actor,
            action="user.update_email",
            target_table="users",
            target_id=str(user_id),
            before={"email": before["email"]},
            after={"email": new_email},
        )
        db.update_user_email(conn, user_id, new_email)
    if role_changed:
        db.record_audit(
            conn,
            actor=actor,
            action="user.update_role",
            target_table="users",
            target_id=str(user_id),
            before={"role": before["role"]},
            after={"role": new_role},
        )
        db.update_user_role(conn, user_id, new_role)
    return {"ok": True}


