"""Remote surface for the desktop operator GUI (admin_gui.py).

admin_gui.py talks to a SQLite file directly when it's running on the same
machine as the database. When the app is hosted somewhere the operator
isn't -- e.g. PythonAnywhere, which offers no SSH or filesystem mounting on
the free tier -- the GUI instead points at this module's routes over
HTTPS, in "remote mode".

Bearer-token authenticated, cookieless, fails closed. Three shapes:

  POST /admin-api/rpc     read-only lookups, dispatched by name from RPC_OPS
  POST /admin-api/action  mutating operations, dispatched by name from
                           ACTION_OPS -- each handler performs its own
                           db.record_audit() call before mutating, lifted
                           verbatim from the matching admin_gui.py closure
  POST /admin-api/sql     the SQL console, mirrored from SqlConsoleTab

Nothing here accepts a client-supplied SQL string except /sql itself --
every other operation is a named, parameterized function, closed by
construction. This is deliberate: the SQL console is already an
intentional full-access escape hatch (gated by "unsafe mode" + audit), and
adding a second, accidental one (e.g. a generic "call any db.* function by
name" dispatcher) would undermine that boundary instead of narrowing it.

GET /admin-api/ping is the auth handshake the GUI uses before trusting a
saved base_url + token.

RPC_OPS/ACTION_OPS are plain module-level functions, not Flask view code,
specifically so admin_gui.py can import and call them directly in "local
mode" (same machine as the DB, no HTTP round trip) -- one implementation
of each operation, shared by both transports, rather than a second copy
of the same logic living in the GUI. See AdminApp.call() in admin_gui.py.
"""

