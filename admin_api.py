def op_overview_stats(conn, params):
    db_path = Path(params["db_path"])
    size = db_path.stat().st_size if db_path.exists() else 0
    wal_path = Path(str(db_path) + "-wal")
    wal_size = wal_path.stat().st_size if wal_path.exists() else 0
    accounts = db.query_one_required(conn, SQL["operator.count_accounts"])["n"]
    active_shifts = db.query_one_required(
        conn,
        SQL["operator.count_active_shifts"],
    )["n"]
    scans_today = db.query_one_required(conn, SQL["operator.count_scans_today_utc"])["n"]
    open_exceptions = db.query_one_required(conn, SQL["operator.count_open_exceptions"])["n"]
    hourly_rows = db.query(
        conn,
        SQL["operator.scans_per_hour_last_24h"],
    )
    counts = [0] * 24
    for row in hourly_rows:
        counts[int(row["hr"])] = row["n"]
    return {
        "db_path": str(db_path),
        "size": size,
        "wal_size": wal_size,
        "accounts": accounts,
        "active_shifts": active_shifts,
        "scans_today": scans_today,
        "open_exceptions": open_exceptions,
        "hourly": counts,
    }


