def act_account_create(conn, actor, params):
    _require(params, "name", "email")
    name = params["name"].strip()
    email = params["email"].strip().lower()
    price_cents = int(params.get("price_per_catch_cents", 0))
    free_allowance = int(params.get("free_allowance", 0))
    account_timezone = params.get("timezone") or "UTC"
    if db.get_user_by_email(conn, email):
        raise ApiError(f"a user with email {email} already exists.")
    new_password = auth.generate_relay_password()
    with db.transaction(conn):
        account_id = db.create_account(
            conn, name, price_cents, free_allowance, timezone=account_timezone
        )
        db.create_user(conn, account_id, email, auth.hash_password(new_password), role="owner")
        db.record_audit(
            conn,
            actor=actor,
            action="account.create",
            target_table="accounts",
            target_id=str(account_id),
            after={"name": name, "email": email},
        )
    return {"account_id": account_id, "email": email, "password": new_password}


def act_account_update(conn, actor, params):
    _require(params, "account_id")
    account_id = int(params["account_id"])
    fields = {
        k: params[k]
        for k in (
            "name",
            "plan",
            "price_per_catch_cents",
            "free_allowance",
            "loose_suffix_len",
            "loose_match_enabled",
            "worker_self_resolve",
            "timezone",
        )
        if k in params
    }
    before = _row(db.get_account(conn, account_id))
    if before is None:
        raise ApiError("account not found", 404)
    # Validate before auditing, so a rejected update leaves no audit row
    # claiming a change that never happened. The database enforces this too
    # (migrations/0009), but a 400 here is a better answer than a 500 out of
    # a trigger, and the operator gets told what the bound is.
    if "loose_suffix_len" in fields:
        try:
            suffix_len = int(fields["loose_suffix_len"])
        except (TypeError, ValueError) as exc:
            raise ApiError("loose_suffix_len must be an integer", 400) from exc
        if not barcode.MIN_SUFFIX_LEN <= suffix_len <= MAX_SUFFIX_LEN:
            raise ApiError(
                f"loose_suffix_len must be between {barcode.MIN_SUFFIX_LEN} and {MAX_SUFFIX_LEN}",
                400,
            )
        fields["loose_suffix_len"] = suffix_len
    db.record_audit(
        conn,
        actor=actor,
        action="account.update",
        target_table="accounts",
        target_id=str(account_id),
        before=before,
        after=fields,
    )
    db.update_account_fields(conn, account_id, **fields)
    return {"ok": True}


