def register_admin_api_routes(app, get_db) -> None:
    token_path = app.config["DB_PATH"].parent / TOKEN_FILENAME
    api_token = _load_or_create_token(token_path)

    def _check_auth():
        # A logged-in owner's browser must never be walkable into these
        # routes -- reject session-cookie auth outright, independent of
        # the bearer check below, rather than merely not requiring it.
        if request.cookies.get(auth.SESSION_COOKIE_NAME):
            return False
        header = request.headers.get("Authorization", "")
        if not header.startswith("Bearer "):
            return False
        supplied = header[len("Bearer ") :]
        return hmac.compare_digest(supplied, api_token)

    bp = Blueprint("admin_api", __name__, url_prefix="/admin-api")

    @bp.before_request
    def _auth_gate():
        if not _check_auth():
            return jsonify({"error": "unauthorized"}), 401
        return None

    @bp.route("/ping", methods=["GET"])
    def ping():
        return jsonify({"ok": True})

    @bp.route("/rpc", methods=["POST"])
    def rpc():
        body = request.get_json(silent=True) or {}
        # `fn` is untrusted JSON: it can be absent, or any type at all.
        # str() keeps the dict lookup total instead of raising on, say, a
        # list, and an unknown name already returns 404 below.
        name = str(body.get("fn") or "")
        handler = RPC_OPS.get(name)
        if handler is None:
            return jsonify({"error": f"unknown operation: {name}"}), 404
        conn = get_db()
        params = dict(body.get("params") or {})
        params["db_path"] = str(app.config["DB_PATH"])
        try:
            result = handler(conn, params)
            return jsonify({"result": result})
        except ApiError as e:
            return jsonify({"error": str(e)}), e.status
        except (ValueError, LookupError) as e:
            return jsonify({"error": str(e)}), 400

    @bp.route("/action", methods=["POST"])
    def action():
        body = request.get_json(silent=True) or {}
        name = str(body.get("fn") or "")  # see rpc() above
        handler = ACTION_OPS.get(name)
        if handler is None:
            return jsonify({"error": f"unknown operation: {name}"}), 404
        conn = get_db()
        actor = f"operator-api:{request.remote_addr}"
        try:
            result = handler(conn, actor, body.get("params") or {})
            return jsonify({"result": result})
        except ApiError as e:
            return jsonify({"error": str(e)}), e.status
        except (ValueError, LookupError) as e:
            return jsonify({"error": str(e)}), 400

    @bp.route("/backup", methods=["POST"])
    def backup_route():
        result = run_backup(app.config["DB_PATH"], app.config["APPEAL_PHOTOS_DIR"])
        return jsonify({"result": result})

    @bp.route("/restore", methods=["POST"])
    def restore_route():
        body = request.get_json(silent=True) or {}
        content_b64 = body.get("content_b64")
        if not content_b64:
            return jsonify({"error": "content_b64 is required"}), 400
        try:
            content = base64.b64decode(content_b64)
        except Exception:
            return jsonify({"error": "invalid content_b64"}), 400
        try:
            run_restore(
                str(body.get("kind") or ""),
                content,
                app.config["DB_PATH"],
                app.config["APPEAL_PHOTOS_DIR"],
            )
            return jsonify({"result": {"ok": True}})
        except ApiError as e:
            return jsonify({"error": str(e)}), e.status
        except FileNotFoundError as e:
            return jsonify({"error": str(e)}), 400

    @bp.route("/sql", methods=["POST"])
    def sql_console():
        body = request.get_json(silent=True) or {}
        conn = get_db()
        actor = f"operator-api:{request.remote_addr}"
        try:
            result = run_sql(conn, body.get("sql") or "", bool(body.get("unsafe")), actor)
            return jsonify({"result": result})
        except ApiError as e:
            return jsonify({"error": str(e)}), e.status

    app.register_blueprint(bp)
