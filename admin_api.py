def op_scan_forensics(conn, params):
    _require(params, "scan_uuid")
    scan_uuid = params["scan_uuid"]
    scan = db.get_scan(conn, scan_uuid)
    if not scan:
        raise ApiError("scan not found", 404)
    session = db.get_session(conn, scan["session_id"])
    shift = db.get_shift(conn, session["shift_id"]) if session else None
    worker = (
        db.query_one(conn, SQL["workers.get_worker"], (session["worker_id"],)) if session else None
    )
    account = db.get_account(conn, shift["account_id"]) if shift else None
    manifest_ids = db.get_shift_manifest_ids(conn, shift["id"]) if shift else []

    norm = barcode.normalize(
        scan["raw_payload"], suffix_len=account["loose_suffix_len"] if account else 8
    )
    raw_bytes = scan["raw_payload"].encode("utf-8", errors="replace")

    idx = manifest_ingest.build_match_index(conn, account, manifest_ids) if account else None
    candidates = {}
    winning_tier = None
    if idx is not None:
        match_result = idx.match(scan["raw_payload"])
        candidates = {int(t): ids for t, ids in match_result.candidates_by_tier.items()}
        winning_tier = int(match_result.tier) if match_result.tier is not None else None

    return {
        "scan": _row(scan),
        "worker": _row(worker),
        "account": _row(account),
        "shift": _row(shift),
        "norm_keys": {int(t): k for t, k in norm.keys.items()},
        "gs1": norm.gs1.__dict__ if norm.gs1 else None,
        "raw_hex": raw_bytes.hex(" "),
        "raw_ascii": scan["raw_payload"],
        "candidates": candidates,
        "winning_tier": winning_tier,
    }


def op_normalizer_match(conn, params):
    _require(params, "raw")
    raw = params["raw"]
    account_id = params.get("account_id")
    account = db.get_account(conn, int(account_id)) if account_id else None
    norm = barcode.normalize(raw, suffix_len=account["loose_suffix_len"] if account else 8)
    match = None
    if account:
        manifest_ids = [m["id"] for m in db.list_committed_manifests(conn, account["id"])]
        idx = manifest_ingest.build_match_index(conn, account, manifest_ids)
        match_result = idx.match(raw)
        match = {
            "tier": int(match_result.tier) if match_result.tier is not None else None,
            "is_resolved": match_result.is_resolved,
            "manifest_line_id": match_result.manifest_line_id,
            "needs_confirmation": match_result.needs_confirmation,
            "candidates_by_tier": {
                int(t): ids for t, ids in match_result.candidates_by_tier.items()
            },
        }
    return {
        "normalized": norm.normalized,
        "gs1": norm.gs1.__dict__ if norm.gs1 else None,
        "gtin_info": norm.gtin_info.__dict__ if norm.gtin_info else None,
        "keys": {int(t): k for t, k in norm.keys.items()},
        "match": match,
    }


