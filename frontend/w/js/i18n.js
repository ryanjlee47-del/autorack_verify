let lang = "en";

export function setLang(value) {
  lang = Object.prototype.hasOwnProperty.call(STRINGS, value) ? value : "en";
  if (typeof document !== "undefined") document.documentElement.lang = lang;
  return lang;
}

export function getLang() {
  return lang;
}

export function T(key, vars) {
  const table = STRINGS[lang];
  let str = Object.prototype.hasOwnProperty.call(table, key) ? table[key] : STRINGS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) str = str.split(`{${k}}`).join(String(v));
  }
  return str;
}
